function mapCatalog(value: unknown, translate: (text: string) => string): unknown {
	if (typeof value === "string") return translate(value);
	if (Array.isArray(value)) return value.map((item) => mapCatalog(item, translate));
	if (value && typeof value === "object") {
		return Object.fromEntries(
			Object.entries(value).map(([key, item]) => [key, mapCatalog(item, translate)]),
		);
	}
	return value;
}

function english(text: string): string {
	if (!/\p{Script=Han}/u.test(text)) return text;
	const translated = en.get(text);
	if (!translated) throw new Error(`Missing English product UI translation: ${text}`);
	return translated;
}

