// Only model responses are authored. Runs, native tool execution, delivery and
// artifact bytes all come from the production Pi ACP worker and authenticated Host.
async function readRuns(page: Page, conversationId: string) {
	const { token } = await getBootstrap(page);
	const response = await page.request.post("/rpc/run.list", {
		headers: { "x-bear-web-dev-token": token },
		data: { conversationId },
	});
	const envelope = await response.json();
	expect(envelope).toMatchObject({ ok: true });
	return (envelope.data as RunListResponse).runs;
}

async function deliveredEntries(page: Page, conversationId: string, runId: string) {
	const { token } = await getBootstrap(page);
	const response = await page.request.post("/rpc/conversation.history", {
		headers: { "x-bear-web-dev-token": token },
		data: { conversationId, limit: 100 },
	});
	const envelope = await response.json();
	expect(envelope).toMatchObject({ ok: true });
	return (envelope.data as ConversationHistoryResponse).entries.filter(
		(entry) =>
			entry.type === "custom_message" &&
			entry.customType === "host_external_agent_result" &&
			typeof entry.details === "object" &&
			entry.details !== null &&
			"runId" in entry.details &&
			entry.details.runId === runId,
	);
}

test("a built-in Pi Run exposes native evidence and a genuinely downloadable Artifact", async ({
	page,
}) => {
	test.setTimeout(60_000);
	await ensureReadyForConversation(page);
	await sendMessage(page, "E2E_DELEGATE_ARTIFACT");
	const thread = page.getByRole("region", { name: zhCN.messages.conversation });
	await expect(thread.getByText("E2E_DELEGATED", { exact: true })).toBeVisible();

	const card = thread.getByRole("article", { name: "E2E_EXTERNAL_WRITE_ARTIFACT", exact: true });
	await expect(card).toHaveAttribute("data-run-status", "completed", { timeout: 30_000 });
	await card.getByRole("button", { name: zhCN.work.timeline.revealDetails }).click();
	const detail = page.getByRole("region", { name: zhCN.work.task.details });
	const instruction = detail
		.getByRole("group")
		.filter({ has: page.getByText(zhCN.work.task.instruction, { exact: true }) });
	await instruction.getByText(zhCN.work.task.instruction, { exact: true }).click();
	await expect(instruction.getByText("E2E_EXTERNAL_WRITE_ARTIFACT", { exact: true })).toBeVisible();
	await expect(detail).toContainText("EXTERNAL_ARTIFACT_DONE");
	const evidence = detail.getByRole("region", { name: zhCN.work.result.evidence });
	const nativeArgs = evidence
		.getByRole("group")
		.filter({ hasText: '"title": "bash"' })
		.filter({ hasText: "E2E_ARTIFACT_VERIFIED" });
	await nativeArgs.getByText("acp.tool_call", { exact: false }).click();
	const args = nativeArgs.getByText('"rawInput":', { exact: false });
	await expect(args).toBeVisible();
	const nativeCall = JSON.parse((await args.textContent())!);
	expect(nativeCall.rawInput.command).toBe(
		"printf 'Artifact generated by the E2E built-in Pi Worker.\\n' | cmp - \"$BEAR_OUTPUT_DIR/e2e-report.txt\" && printf 'E2E_ARTIFACT_VERIFIED\\n'",
	);
	const nativeCheck = evidence
		.getByRole("group")
		.filter({ hasText: '"status": "completed"' })
		.filter({ hasText: `"toolCallId": ${JSON.stringify(nativeCall.toolCallId)}` });
	await nativeCheck.getByText("acp.tool_call_update", { exact: false }).click();
	const output = nativeCheck.getByText('"rawOutput":', { exact: false });
	await expect(output).toBeVisible();
	expect(JSON.parse((await output.textContent())!)).toMatchObject({
		toolCallId: nativeCall.toolCallId,
		status: "completed",
		rawOutput: { content: [{ type: "text", text: "E2E_ARTIFACT_VERIFIED" }] },
	});
	await expect(detail.getByRole("button", { name: zhCN.work.interrupt, exact: true })).toHaveCount(
		0,
	);
	const artifact = detail.getByRole("button", {
		name: `${zhCN.work.timeline.viewArtifacts}: e2e-report.txt`,
		exact: true,
	});
	await expect(artifact).toBeVisible();
	const preview = page.getByRole("dialog", { name: "e2e-report.txt" });
	await expect(preview).toHaveCount(0);
	await artifact.click();
	await expect(preview).toBeVisible();
	await expect(
		preview.getByText("Artifact generated by the E2E built-in Pi Worker."),
	).toBeVisible();
	await expect(preview.getByRole("region", { name: zhCN.work.result.provenance })).toBeVisible();
	const conversationId = await activeConversationId(page);
	const digest = (await readRuns(page, conversationId))[0]?.artifacts[0]?.sha256;
	if (!digest) throw new Error("Completed Artifact has no digest");
	await expect(preview.getByText(digest, { exact: true })).toBeVisible();

	const downloadPromise = page.waitForEvent("download");
	await preview.getByRole("button", { name: zhCN.work.download }).click();
	const download = await downloadPromise;
	expect(download.suggestedFilename()).toBe("e2e-report.txt");
	const path = await download.path();
	if (!path) throw new Error("Artifact download has no local file");
	expect(await readFile(path, "utf8")).toBe("Artifact generated by the E2E built-in Pi Worker.\n");
});

