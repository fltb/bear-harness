test("a generated workbook downloads with the real A1:E5 values", async ({ page }) => {
	test.setTimeout(60_000);
	await ensureReadyForConversation(page);
	await sendMessage(page, "E2E_DELEGATE_XLSX");
	const card = page
		.getByRole("region", { name: zhCN.messages.conversation })
		.getByRole("article", { name: "E2E_EXTERNAL_WRITE_XLSX", exact: true });
	await expect
		.poll(
			async () => {
				const status = await card.getAttribute("data-run-status");
				return status && ["completed", "failed", "cancelled", "forced_termination"].includes(status)
					? status
					: undefined;
			},
			{ timeout: 30_000 },
		)
		.toBeTruthy();
	await card.getByRole("button", { name: zhCN.work.timeline.revealDetails }).click();
	const detail = page.getByRole("region", { name: zhCN.work.task.details });
	const runStatus = await card.getAttribute("data-run-status");
	if (runStatus !== "completed") {
		await expect(detail).not.toContainText("正在加载任务…");
		const acpError = detail.getByText("acp.error", { exact: false });
		if ((await acpError.count()) === 1) await acpError.click();
		for (const update of await detail.getByText("acp.tool_call_update", { exact: false }).all()) {
			await update.click();
		}
		throw new Error(`Workbook Run settled as ${runStatus}: ${await detail.innerText()}`);
	}
	await expect(detail).toContainText("E2E_XLSX_VERIFIED: A1:E5 = 1..25");
	const result = page.getByRole("dialog", { name: "e2e-grid.xlsx" });
	await expect(result).toHaveCount(0);
	await detail
		.getByRole("button", {
			name: `${zhCN.work.timeline.viewArtifacts}: e2e-grid.xlsx`,
			exact: true,
		})
		.click();
	await expect(result.getByRole("region", { name: zhCN.work.result.provenance })).toBeVisible();
	const downloading = page.waitForEvent("download");
	await result.getByRole("button", { name: zhCN.work.download }).click();
	const download = await downloading;
	expect(download.suggestedFilename()).toBe("e2e-grid.xlsx");
	const path = await download.path();
	if (!path) throw new Error("Workbook download has no local file");
	// Inspect the downloaded ZIP, not the provider's claimed summary or Host metadata.
	const { stdout } = await promisify(execFile)(
		"python3",
		[
			"-c",
			`
import json, sys
from zipfile import ZipFile
from xml.etree import ElementTree as ET
with ZipFile(sys.argv[1]) as book:
    assert book.testzip() is None
    root = ET.fromstring(book.read("xl/worksheets/sheet1.xml"))
ns = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
print(json.dumps({c.attrib["r"]: int(c.find("s:v", ns).text) for c in root.findall(".//s:c", ns)}))
`,
			path,
		],
		{ timeout: 10_000 },
	);
	const expected = Object.fromEntries(
		Array.from({ length: 25 }, (_, index) => [
			`${String.fromCharCode(65 + (index % 5))}${Math.floor(index / 5) + 1}`,
			index + 1,
		]),
	);
	expect(JSON.parse(stdout)).toEqual(expected);
});

test("a busy origin receives one durable result while another conversation remains selected", async ({
	page,
}) => {
	test.setTimeout(90_000);
	await ensureReadyForConversation(page);
	const origin = await activeConversationId(page);
	const worker = providerHold(page);
	const originTurn = providerHold(page);
	try {
		await sendMessage(page, `E2E_DELEGATE_ARTIFACT_HOLD_${worker.id}`);
		await worker.entered();
		await expect(page.getByTestId("conversation-activity")).toBeHidden();
		const [run] = await readRuns(page, origin);
		if (!run) throw new Error("Delegation produced no Run");
		await sendMessage(page, `E2E_WAIT_TEXT_${originTurn.id}`);
		await originTurn.entered();
		const [createdResponse] = await Promise.all([
			page.waitForResponse(
				(response) =>
					response.request().method() === "POST" &&
					response.url().includes("/rpc/conversation.create"),
			),
			page.getByRole("button", { name: zhCN.sidebar.newConversation, exact: true }).click(),
		]);
		const created = await createdResponse.json();
		expect(created).toMatchObject({ ok: true, data: { conversationId: expect.any(String) } });
		const other = await activeConversationId(page, created.data.conversationId);
		expect(other).not.toBe(origin);
		await worker.release();
		await expect.poll(async () => (await readRuns(page, origin))[0]?.status).toBe("completed");
		expect((await readRuns(page, origin))[0]?.resultReportedAt).toBeUndefined();
		expect(await deliveredEntries(page, origin, run.id)).toEqual([]);
		await activeConversationId(page, other);
		await expect(page.getByRole("dialog", { name: "e2e-report.txt" })).toHaveCount(0);
		await originTurn.release();
		await expect
			.poll(async () => (await deliveredEntries(page, origin, run.id)).length, { timeout: 30_000 })
			.toBe(1);
		await expect
			.poll(async () => (await readRuns(page, origin))[0]?.resultReportedAt)
			.toEqual(expect.any(String));
		expect(await deliveredEntries(page, other, run.id)).toEqual([]);
		await activeConversationId(page, other);
		await page.reload();
		await activeConversationId(page, other);
		expect(await deliveredEntries(page, origin, run.id)).toHaveLength(1);
		await page.locator(`[data-conversation-id="${origin}"]`).click();
		await expect(
			page.getByRole("button", {
				name: `${zhCN.work.timeline.viewArtifacts}: e2e-report.txt`,
				exact: true,
			}),
		).toBeVisible();
		await expect(page.getByRole("dialog", { name: "e2e-report.txt" })).toHaveCount(0);
	} finally {
		await worker.release();
		await originTurn.release();
	}
});

test("native Worker interruption exposes resume and cancellation without claiming completion", async ({
	page,
}) => {
	test.setTimeout(60_000);
	await ensureReadyForConversation(page);
	const hold = providerHold(page);
	try {
		await sendMessage(page, `E2E_DELEGATE_ARTIFACT_HOLD_${hold.id}`);
		await hold.entered();
		const card = page
			.getByRole("region", { name: zhCN.messages.conversation })
			.getByRole("article", { name: `E2E_EXTERNAL_WRITE_ARTIFACT_HOLD_${hold.id}`, exact: true });
		await card.getByRole("button", { name: zhCN.work.timeline.revealDetails }).click();
		const detail = page.getByRole("region", { name: zhCN.work.task.details });
		await detail.getByRole("button", { name: zhCN.work.interrupt, exact: true }).click();
		await hold.cancelled();
		await expect(card).toHaveAttribute("data-run-status", "interrupted");
		await expect(detail.getByRole("button", { name: zhCN.work.resume, exact: true })).toBeEnabled();
		await detail.getByRole("button", { name: zhCN.work.timeline.stopRun, exact: true }).click();
		await expect(card).toHaveAttribute("data-run-status", "cancelled");
		await expect(detail.getByRole("button", { name: zhCN.work.resume, exact: true })).toHaveCount(
			0,
		);
		await expect(page.getByRole("dialog", { name: "e2e-report.txt" })).toHaveCount(0);
	} finally {
		await hold.release();
	}
});

test("resuming a confirmed native pause completes the same Run", async ({ page }) => {
	test.setTimeout(60_000);
	await ensureReadyForConversation(page);
	const origin = await activeConversationId(page);
	const hold = providerHold(page);
	try {
		await sendMessage(page, `E2E_DELEGATE_ARTIFACT_HOLD_${hold.id}`);
		await hold.entered();
		const card = page
			.getByRole("region", { name: zhCN.messages.conversation })
			.getByRole("article", { name: `E2E_EXTERNAL_WRITE_ARTIFACT_HOLD_${hold.id}`, exact: true });
		const runId = await card.getAttribute("data-run-id");
		await card.getByRole("button", { name: zhCN.work.timeline.revealDetails }).click();
		const detail = page.getByRole("region", { name: zhCN.work.task.details });
		await detail.getByRole("button", { name: zhCN.work.interrupt, exact: true }).click();
		await hold.cancelled();
		await expect(card).toHaveAttribute("data-run-status", "interrupted");
		await hold.release();
		await detail.getByRole("button", { name: zhCN.work.resume, exact: true }).click();
		await expect(card).toHaveAttribute("data-run-status", "completed", { timeout: 30_000 });
		expect((await readRuns(page, origin)).map((run) => run.id)).toEqual([runId]);
		await expect(
			card.getByRole("button", {
				name: `${zhCN.work.timeline.viewArtifacts}: e2e-report.txt`,
				exact: true,
			}),
		).toBeVisible();
		await expect(page.getByRole("dialog", { name: "e2e-report.txt" })).toHaveCount(0);
	} finally {
		await hold.release();
	}
});

